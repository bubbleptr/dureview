export function ProviderMark({ provider, className }: { provider: string; className?: string }) {
  if (!isProviderName(provider)) return null;
  if (provider === "openai-codex" || provider === "openai") return <OpenAiMark className={className} />;
  if (provider === "github-copilot") return <CopilotMark className={className} />;
  if (provider === "xai") return <XaiMark className={className} />;
  if (provider === "openrouter") return <OpenRouterMark className={className} />;
  return <DeepSeekMark className={className} />;
}

export function ProviderLabel({ provider, children }: { provider: string; children: ReactNode }) {
  return (
    <span className="inline-flex min-w-0 items-center gap-2">
      <ProviderMark provider={provider} />
      <span className="min-w-0">{children}</span>
    </span>
  );
}
