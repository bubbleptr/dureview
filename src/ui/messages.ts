export function seriesLabel(name: string, locale: Locale): string {
  const key = SERIES_KEYS[name];
  if (!key) return name;
  return messages[locale].series[key];
}

const RESET_LABELS: Record<string, Record<Locale, string>> = {
  provider: { en: "provider", "zh-CN": "提供方" },
  model: { en: "model", "zh-CN": "模型" },
  thinking: { en: "thinking", "zh-CN": "思考" },
  "default trigger": { en: "default trigger", "zh-CN": "默认触发" },
  "skip drafts": { en: "skip drafts", "zh-CN": "跳过草稿" },
  "checkout ttl": { en: "checkout ttl", "zh-CN": "检出保留" },
};

export function localizeKnown(locale: Locale, text: string): string {
  if (locale === "en") return text;
  const english = messages.en.server;
  const chinese = messages["zh-CN"].server;
  for (const key of Object.keys(english) as Array<keyof typeof english>) {
    if (english[key] === text) return chinese[key];
  }
  const unknownModel = /^Unknown model ([^/\s]+)\/(\S+)\.$/.exec(text);
  if (unknownModel?.[1] && unknownModel[2]) return fillServer(chinese.unknownModel, { provider: unknownModel[1], model: unknownModel[2] });
  const thinking = /^Thinking level (\S+) is not supported by ([^/\s]+)\/(\S+)\. Supported levels: (.+)\.$/.exec(text);
  if (thinking?.[1] && thinking[2] && thinking[3] && thinking[4]) {
    return fillServer(chinese.thinkingUnsupported, { level: thinking[1], provider: thinking[2], model: thinking[3], list: thinking[4] });
  }
  const resetting = /^Resetting (.+) leaves a model and thinking level that do not match\. Change them together, then save\.$/.exec(text);
  if (resetting?.[1]) {
    const label = RESET_LABELS[resetting[1]]?.[locale] ?? resetting[1];
    return fillServer(chinese.resetting, { label });
  }
  const appStatus = /^GitHub could not read the app \((\d+)\)\.$/.exec(text);
  if (appStatus?.[1]) return fillServer(chinese.githubAppStatus, { status: appStatus[1] });
  const listStatus = /^GitHub could not list installations \((\d+)\)\.$/.exec(text);
  if (listStatus?.[1]) return fillServer(chinese.githubListStatus, { status: listStatus[1] });
  return text;
}

function fillServer(template: string, vars: Record<string, string>): string {
  return template.replace(/\{([A-Za-z0-9]+)\}/g, (_, key: string) => vars[key] ?? "");
}
